import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const t0 = Date.now();
await p.locator('.mr-search').fill('办公 口');
await p.keyboard.press('Enter');
await p.waitForTimeout(2500);
const st = await p.evaluate(() => ({ cards: document.querySelectorAll('.mr-card').length, state: (document.querySelector('.mr-state') || {}).textContent || '', first: (document.querySelector('.mr-card .mr-title') || {}).textContent?.slice(0, 20) }));
console.log('search 办公 口:', JSON.stringify(st), 'elapsed', Date.now() - t0, 'ms');
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-search.png' });
await b.close();