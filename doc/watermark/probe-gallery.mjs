import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds/post/5', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(6000);
const info = await p.evaluate(() => ({ gcells: document.querySelectorAll('.md-gcell').length, galleries: document.querySelectorAll('.md-gallery').length, blocks: document.querySelectorAll('.md-p').length, state: (document.querySelector('.md-state') || {}).textContent || '' }));
console.log('page:', JSON.stringify(info));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/lb-pre.png' });
await b.close();