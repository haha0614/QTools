import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
await p.locator('.mr-card').nth(7).click();
await p.waitForTimeout(1800);
const savedId = await p.evaluate(() => { const raw = window.localStorage.getItem('ms.mrds.lastSeen'); return raw ? JSON.parse(raw).id : null; });
console.log('saved id:', savedId);
await p.locator('.mr-sheet button', { hasText: '关闭' }).click().catch(() => {});
await p.waitForTimeout(600);
await p.reload({ waitUntil: 'networkidle' });
await p.waitForTimeout(3200);
const before = await p.evaluate((id) => ({ bar: !!document.querySelector('.mr-resume'), inList: !!document.querySelector('[data-post-id="' + id + '"]') }), savedId);
console.log('before locate:', JSON.stringify(before));
await p.locator('.mr-resume button').first().click();
await p.waitForTimeout(1200);
const mid = await p.evaluate(() => ({ hit: document.querySelectorAll('.mr-hit').length, err: (document.querySelector('.mr-err') || {}).textContent || '', bar: !!document.querySelector('.mr-resume'), cards: document.querySelectorAll('[data-post-id]').length }));
console.log('after click 1.2s:', JSON.stringify(mid));
await p.waitForTimeout(2500);
const after = await p.evaluate(() => ({ hit: document.querySelectorAll('.mr-hit').length, bar: !!document.querySelector('.mr-resume') }));
console.log('after 3.7s:', JSON.stringify(after));
await b.close();