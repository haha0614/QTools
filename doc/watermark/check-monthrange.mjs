import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 929 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(2500);
await p.locator('.mr-dates .mr-chip', { hasText: '按月' }).click();
await p.waitForTimeout(600);
const inputs = p.locator('.mr-datepicker input');
await inputs.nth(0).click();
await inputs.nth(0).fill('2026-11');
await p.keyboard.press('Enter');
await p.waitForTimeout(400);
await inputs.nth(1).fill('2026-11');
await p.keyboard.press('Enter');
await p.waitForTimeout(3000);
const st = await p.evaluate(() => ({ label: (document.querySelector('.mr-date-label') || {}).textContent || '', cards: document.querySelectorAll('.mr-card').length, state: (document.querySelector('.mr-state') || {}).textContent || '' }));
console.log('month range result:', JSON.stringify(st));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-monthrange.png' });
await b.close();