import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 929 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3500);
const cards = await p.evaluate(() => [...document.querySelectorAll('.mr-card')].slice(0, 6).map((c) => (c.innerText || '').split('\n').filter(Boolean).filter((x) => x !== '▶').slice(0, 2).join(' | ')));
console.log(JSON.stringify(cards, null, 0));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-order2.png' });
await b.close();