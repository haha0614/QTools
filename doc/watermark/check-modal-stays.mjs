import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(4500);
const beforeY = await p.evaluate(() => Math.round(window.scrollY));
await p.evaluate(() => { const el = document.querySelector('[data-post-id]'); el.click(); });
await p.waitForTimeout(1500);
const [tab] = await Promise.all([ctx.waitForEvent('page'), p.locator('.mr-sheet-head button', { hasText: '展开整页' }).click()]);
await tab.waitForLoadState('domcontentloaded');
console.log('新标签:', tab.url().slice(-20));
await tab.close();
await p.bringToFront();
await p.waitForTimeout(800);
const st = await p.evaluate(() => ({ mask: !!document.querySelector('.mr-mask'), title: (document.querySelector('.md-title') || {}).textContent?.slice(0, 12), y: Math.round(window.scrollY) }));
console.log('回到原标签:', JSON.stringify(st), st.mask ? '（弹窗仍开着 ✓）' : '（弹窗被关了 ✗）');
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/modal-stays.png' });
await b.close();