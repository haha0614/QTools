import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
// 截取转场三个时刻：起点、飞行中、落位后
const card = p.locator('.mr-card').first();
await card.scrollIntoViewIfNeeded();
await p.waitForTimeout(600);
await card.click({ position: { x: 60, y: 40 } });
await p.waitForTimeout(60);
const mid1 = await p.evaluate(() => ({ hero: document.querySelectorAll('.mr-hero').length, moving: document.querySelectorAll('.mr-hero.moving').length, mask: !!document.querySelector('.mr-mask'), sheetHidden: !!document.querySelector('.mr-sheet-hero') }));
console.log('t≈60ms:', JSON.stringify(mid1));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/hero-1.png' });
await p.waitForTimeout(140);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/hero-2.png' });
await p.waitForTimeout(600);
const done = await p.evaluate(() => ({ hero: document.querySelectorAll('.mr-hero').length, sheet: !!document.querySelector('.mr-sheet'), stageVisible: (() => { const s = document.querySelector('.md-hero-target'); return s ? getComputedStyle(s).opacity : null; })(), title: (document.querySelector('.md-hero-title') || {}).textContent?.slice(0, 18) }));
console.log('t≈800ms:', JSON.stringify(done));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/hero-3.png' });
await b.close();