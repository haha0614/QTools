import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 360, height: 800 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.locator('.mr-filter-toggle').click();
await p.waitForTimeout(500);
const inputs = await p.evaluate(() => [...document.querySelectorAll('.mr-datepicker')].map((e) => ({ w: Math.round(e.getBoundingClientRect().width), right: Math.round(e.getBoundingClientRect().right) })));
console.log('pickers:', JSON.stringify(inputs));
await p.locator('.mr-datepicker').first().click();
await p.waitForTimeout(900);
const panel = await p.evaluate(() => { const el = document.querySelector('.el-picker-panel'); if (!el) return null; const r = el.getBoundingClientRect(); return { w: Math.round(r.width), left: Math.round(r.left), right: Math.round(r.right), vw: window.innerWidth, overflow: r.right > window.innerWidth + 1 || r.left < -1 }; });
console.log('panel:', JSON.stringify(panel));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/m-datepicker.png' });
await b.close();