import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 360, height: 800 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(4500);
const st = await p.evaluate(() => ({ viewsOutsidePanel: !!document.querySelector('.mr-bar > .mr-views'), viewsInsidePanel: !!document.querySelector('.mr-more-filters .mr-views'), viewsVisibleWithoutOpening: (() => { const v = document.querySelector('.mr-bar > .mr-views'); return v ? getComputedStyle(v).display : null; })() }));
console.log('views:', JSON.stringify(st));
await p.locator('.mr-view', { hasText: '列表' }).click();
await p.waitForTimeout(1800);
const row = await p.evaluate(() => {
  const r = document.querySelector('.mr-row');
  if (!r) return null;
  const cover = r.querySelector('.mr-row-cover');
  const meta = r.querySelector('.mr-meta');
  const title = r.querySelector('.mr-title');
  const cr = cover.getBoundingClientRect(), mr = meta.getBoundingClientRect(), tr = title.getBoundingClientRect();
  return { coverRight: Math.round(cr.right), titleLeft: Math.round(tr.left), metaTop: Math.round(mr.top), metaH: Math.round(mr.height), titleTop: Math.round(tr.top), sameRowAsTitle: Math.abs(mr.top - tr.top) < 60, metaW: Math.round(mr.width), rowH: Math.round(r.getBoundingClientRect().height) };
});
console.log('list row:', JSON.stringify(row));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/m-list2.png' });
await b.close();