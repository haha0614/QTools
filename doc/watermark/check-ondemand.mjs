import { chromium } from 'playwright-core';
const id = process.argv[2];
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--autoplay-policy=no-user-gesture-required','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
const calls = [];
p.on('request', (r) => { if (r.url().indexOf('/prefetch') >= 0) calls.push(r.method()); });
await p.goto('http://localhost/tool/mrds/post/' + id, { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const before = await p.evaluate(() => ({ imgs: document.querySelectorAll('.md-gcell').length, txt: (document.querySelector('.md-content') || {}).innerText || '' }));
console.log('before:', JSON.stringify({ imgs: before.imgs, txt: before.txt.slice(0, 40) }), 'prefetch calls:', calls.length);
await p.waitForTimeout(25000);
const after = await p.evaluate(() => { const v = document.querySelector('video'); return { imgs: document.querySelectorAll('.md-gcell').length, ok: [...document.querySelectorAll('.md-gcell img')].filter((i) => i.naturalWidth > 0).length, video: v ? { dur: Math.round(v.duration), paused: v.paused } : null }; });
console.log('after 28s:', JSON.stringify(after));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-on-demand.png' });
await b.close();