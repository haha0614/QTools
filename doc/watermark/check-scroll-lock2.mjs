import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e.message).slice(0, 90)));
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.evaluate(() => window.scrollTo(0, 900));
await p.waitForTimeout(400);
const before = await p.evaluate(() => Math.round(window.scrollY));
await p.locator('.mr-card').first().click();
await p.waitForTimeout(2200);
const locked = await p.evaluate(() => ({ pos: document.body.style.position, top: document.body.style.top }));
await p.mouse.move(180, 520);
await p.mouse.wheel(0, 1500);
await p.waitForTimeout(700);
const during = await p.evaluate(() => Math.round(window.scrollY));
console.log('打开后:', JSON.stringify(locked), '| 背后 scrollY:', before, '→', during, before === during ? '（没动 ✓）' : '（动了 ✗）');
await p.locator('.mr-sheet-head button', { hasText: '关闭' }).click();
await p.waitForTimeout(700);
const after = await p.evaluate(() => ({ pos: document.body.style.position || '(空)', y: Math.round(window.scrollY) }));
console.log('关闭后:', JSON.stringify(after), '| errors:', JSON.stringify(errs.slice(0,2)));
await b.close();