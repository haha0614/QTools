import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e.message).slice(0, 120)));
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const card = p.locator('.mr-grid .mr-card').nth(2);
await card.scrollIntoViewIfNeeded();
await p.waitForTimeout(500);
const origin = await p.evaluate(() => { const c = document.querySelectorAll('.mr-grid .mr-card')[2]; const r = c.getBoundingClientRect(); return Math.round(r.left + r.width / 2) + ' ' + Math.round(r.top + r.height / 2); });
await card.click();
const probes = [];
for (const w of [60, 80, 100, 150]) {
  await p.waitForTimeout(w);
  probes.push(await p.evaluate(() => { const s = document.querySelector('.mr-sheet'); if (!s) return { sheet: false }; const cs = getComputedStyle(s); return { t: cs.transform.slice(0, 34), o: Number(cs.opacity).toFixed(2), origin: cs.transformOrigin }; }));
}
console.log('card center:', origin);
console.log('probes:', JSON.stringify(probes));
await p.waitForTimeout(500);
const end = await p.evaluate(() => { const s = document.querySelector('.mr-sheet'); const cs = getComputedStyle(s); return { t: cs.transform, o: cs.opacity, heroes: document.querySelectorAll('.mr-hero').length }; });
console.log('end:', JSON.stringify(end));
console.log('page errors:', JSON.stringify(errs.slice(0, 3)));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/zoom-open.png' });
await p.locator('.mr-sheet-head button', { hasText: '关闭' }).click();
await p.waitForTimeout(500);
const closed = await p.evaluate(() => ({ mask: document.querySelectorAll('.mr-mask').length }));
console.log('after close:', JSON.stringify(closed));
await b.close();