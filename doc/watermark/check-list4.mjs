import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 360, height: 800 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.locator('.mr-view', { hasText: '列表' }).click();
await p.waitForTimeout(2000);
const row = await p.evaluate(() => {
  const r = document.querySelector('.mr-row');
  if (!r) return { none: true };
  const cover = r.querySelector('.mr-row-cover').getBoundingClientRect();
  const side = r.querySelector('.mr-row-side');
  const sr = side.getBoundingClientRect();
  const tr = r.querySelector('.mr-title').getBoundingClientRect();
  return { coverRight: Math.round(cover.right), titleLeft: Math.round(tr.left), dateTop: Math.round(sr.top), titleBottom: Math.round(tr.bottom), dateRight: Math.round(sr.right), dateH: Math.round(sr.height), rowH: Math.round(r.getBoundingClientRect().height) };
});
console.log('row:', JSON.stringify(row));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/m-list3.png' });
await b.close();