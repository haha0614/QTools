import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const card = p.locator('.mr-grid .mr-card').nth(1);
await card.scrollIntoViewIfNeeded();
await p.waitForTimeout(600);
const from = await p.evaluate(() => { const c = document.querySelectorAll('.mr-grid .mr-card')[1].querySelector('.mr-cover'); const r = c.getBoundingClientRect(); return { x: Math.round(r.x), y: Math.round(r.y), w: Math.round(r.width), h: Math.round(r.height) }; });
await card.click();
await p.waitForTimeout(150);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/hero-a.png' });
await p.waitForTimeout(120);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/hero-b.png' });
await p.waitForTimeout(700);
const to = await p.evaluate(() => { const s = document.querySelector('.md-hero-target'); const r = s.getBoundingClientRect(); return { x: Math.round(r.x), y: Math.round(r.y), w: Math.round(r.width), h: Math.round(r.height) }; });
console.log('from card cover:', JSON.stringify(from), '-> to stage:', JSON.stringify(to));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/hero-c.png' });
await b.close();