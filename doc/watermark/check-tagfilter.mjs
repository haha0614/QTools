import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 1000 } });
const p = await ctx.newPage();
const reqs = [];
p.on('request', (r) => { if (r.url().indexOf('/tool/web/posts') >= 0) reqs.push(decodeURIComponent(r.url()).slice(-90)); });
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
// 打开抽屉，搜索伪娘
await p.locator('.mr-chip-more').click();
await p.waitForTimeout(800);
await p.locator('.mr-drawer-search').fill('伪娘');
await p.waitForTimeout(600);
const found = await p.evaluate(() => [...document.querySelectorAll('.mr-drawer-tag')].map((t) => t.textContent.trim().slice(0, 24)));
console.log('drawer tags for 伪娘:', JSON.stringify(found));
await p.locator('.mr-drawer-pick').first().click();
await p.waitForTimeout(2200);
const after = await p.evaluate(() => ({ cards: document.querySelectorAll('.mr-card').length, state: (document.querySelector('.mr-state') || {}).textContent || '', titles: [...document.querySelectorAll('.mr-card .mr-title')].slice(0, 2).map((t) => t.textContent.slice(0, 18)) }));
console.log('after select:', JSON.stringify(after));
console.log('requests:', JSON.stringify(reqs.slice(-3), null, 0));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-tagfilter.png' });
await b.close();