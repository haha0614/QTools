import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--autoplay-policy=no-user-gesture-required','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
// 1) 多视频切换
await p.goto('http://localhost/tool/mrds/post/2', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3500);
const vids = await p.evaluate(() => ({ buttons: document.querySelectorAll('.md-vbtn').length, labels: [...document.querySelectorAll('.md-vbtn')].map((x) => x.textContent.trim()) }));
console.log('video switcher:', JSON.stringify(vids));
await p.evaluate(() => { const v = document.querySelector('video'); if (v) { v.muted = true; v.play().catch(() => {}); } });
await p.waitForTimeout(4000);
const playing = await p.evaluate(() => { const v = document.querySelector('video'); return v ? { t: Math.round(v.currentTime), dur: Math.round(v.duration), paused: v.paused } : null; });
console.log('playing video1:', JSON.stringify(playing));
await p.locator('.md-vbtn', { hasText: '视频 2' }).click();
await p.waitForTimeout(6000);
const second = await p.evaluate(() => { const v = document.querySelector('video'); return v ? { t: Math.round(v.currentTime), dur: Math.round(v.duration), ready: v.readyState } : null; });
console.log('after switch to video2:', JSON.stringify(second));
// 2) 上次浏览位置
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
await p.locator('.mr-card').nth(5).click();
await p.waitForTimeout(2000);
await p.locator('.mr-sheet button', { hasText: '关闭' }).click().catch(() => {});
await p.waitForTimeout(800);
await p.reload({ waitUntil: 'networkidle' });
await p.waitForTimeout(3200);
const bar = await p.evaluate(() => { const el = document.querySelector('.mr-resume'); return el ? el.querySelector('.mr-resume-text').textContent.trim().slice(0, 30) : null; });
console.log('resume bar:', JSON.stringify(bar));
await p.locator('.mr-resume .mr-chip').first().click();
await p.waitForTimeout(2500);
const hit = await p.evaluate(() => ({ marked: document.querySelectorAll('.mr-hit').length, barGone: !document.querySelector('.mr-resume') }));
console.log('after locate:', JSON.stringify(hit));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-resume.png' });
await b.close();