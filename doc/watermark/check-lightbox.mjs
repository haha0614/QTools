import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e.message).slice(0, 120)));
await p.goto('http://localhost/tool/mrds/post/5', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(4000);
const cells = await p.locator('.md-gcell').count();
console.log('gallery cells:', cells);
await p.locator('.md-gcell').nth(1).click();
await p.waitForTimeout(700);
const st = await p.evaluate(() => { const lb = document.querySelector('.md-lb'); if (!lb) return { open: false }; const img = lb.querySelector('.md-lb-img'); return { open: true, count: (lb.querySelector('.md-lb-count') || {}).textContent, src: (img.src || '').slice(-14), zoom: img.style.transform }; });
console.log('lightbox:', JSON.stringify(st));
// 左右切换
await p.locator('.md-lb-nav.next').click();
await p.waitForTimeout(400);
const afterNext = await p.evaluate(() => (document.querySelector('.md-lb-count') || {}).textContent);
console.log('after next:', afterNext);
// 滚轮放大
await p.locator('.md-lb-img').hover();
await p.mouse.wheel(0, -300);
await p.waitForTimeout(300);
await p.mouse.wheel(0, -300);
await p.waitForTimeout(300);
const zoomed = await p.evaluate(() => (document.querySelector('.md-lb-img') || {}).style?.transform);
console.log('after wheel:', zoomed);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/lightbox.png' });
await p.keyboard.press('Escape');
await p.waitForTimeout(400);
console.log('closed:', await p.evaluate(() => !document.querySelector('.md-lb')), 'errors:', JSON.stringify(errs.slice(0,2)));
await b.close();