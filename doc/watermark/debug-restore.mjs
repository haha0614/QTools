import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 120)); });
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.evaluate(() => window.scrollTo(0, 4000));
await p.waitForTimeout(1200);
await p.locator('[data-post-id]').nth(3).click();
await p.waitForTimeout(1800);
await p.locator('.mr-sheet-head button', { hasText: '展开整页' }).click();
await p.waitForTimeout(2500);
const snap = await p.evaluate(() => { const raw = sessionStorage.getItem('ms.mrds.listState'); if (!raw) return { none: true }; const o = JSON.parse(raw); return { rows: o.rows.length, scrollY: o.scrollY, page: o.page }; });
console.log('离开时的快照:', JSON.stringify(snap), '| 当前 URL:', p.url());
await p.locator('.mp-back').click();
await p.waitForTimeout(300);
const q = await p.evaluate(() => ({ url: location.pathname + location.search, hasSnap: !!sessionStorage.getItem('ms.mrds.listState') }));
console.log('点击返回后 URL:', JSON.stringify(q));
await p.waitForTimeout(3000);
const after = await p.evaluate(() => ({ y: Math.round(window.scrollY), cards: document.querySelectorAll('[data-post-id]').length, url: location.pathname + location.search }));
console.log('落定后:', JSON.stringify(after));
await b.close();