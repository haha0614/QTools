import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 360, height: 800 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.locator('.mr-filter-toggle').click();
await p.waitForTimeout(500);
await p.evaluate(() => { const el = document.querySelector('.mr-date-row'); if (el) el.scrollIntoView({ block: 'center' }); });
await p.waitForTimeout(600);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/m-date3.png' });
await b.close();