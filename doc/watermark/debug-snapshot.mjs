import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(4500);
for (let i = 0; i < 5; i++) { await p.mouse.wheel(0, 1200); await p.waitForTimeout(400); }
await p.waitForTimeout(800);
const y0 = await p.evaluate(() => Math.round(window.scrollY));
await p.evaluate(() => { const cards=[...document.querySelectorAll('[data-post-id]')]; const vis=cards.find((e)=>{const r=e.getBoundingClientRect();return r.top>100&&r.bottom<window.innerHeight;})||cards[0]; vis.click(); });
await p.waitForTimeout(1500);
const yBeforeNav = await p.evaluate(() => Math.round(window.scrollY));
await p.locator('.mr-sheet-head button', { hasText: '展开整页' }).click();
await p.waitForTimeout(200);
const snap = await p.evaluate(() => { const raw = sessionStorage.getItem('ms.mrds.listState'); return raw ? JSON.parse(raw) : 'none'; });
console.log('滚动 y0 =', y0, '| 导航前 y =', yBeforeNav, '| 快照 =', JSON.stringify(snap));
await p.waitForTimeout(2000);
console.log('整页 URL =', p.url());
await p.locator('.mp-back').click();
await p.waitForTimeout(2500);
console.log('返回后 y =', await p.evaluate(() => Math.round(window.scrollY)));
await b.close();