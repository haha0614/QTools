import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 929 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(2500);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-list2.png' });
await p.locator('.mr-card, .mr-cover').first().click();
await p.waitForTimeout(3500);
const box = await p.evaluate(() => { const s = document.querySelector('.mr-sheet'); const side = document.querySelector('.md-side'); const g = document.querySelector('.md-gallery'); const r = (x) => x ? [Math.round(x.getBoundingClientRect().width), Math.round(x.getBoundingClientRect().height)] : null; return { sheet: r(s), side: r(side), gallery: r(g), cols: g ? getComputedStyle(g).columnCount : null }; });
console.log('modal box:', JSON.stringify(box));
const d = await p.evaluate(() => { const imgs = [...document.querySelectorAll('.mr-sheet img')]; return { total: imgs.length, ok: imgs.filter((i) => i.naturalWidth > 0).length }; });
console.log('modal imgs:', JSON.stringify(d));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-modal.png' });
await b.close();