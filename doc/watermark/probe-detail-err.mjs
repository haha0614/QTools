import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1400, height: 900 } });
const p = await ctx.newPage();
const logs = [];
p.on('console', (m) => logs.push(m.type() + ': ' + m.text().slice(0, 200)));
p.on('pageerror', (e) => logs.push('PAGEERROR: ' + String(e.message).slice(0, 300)));
p.on('requestfailed', (r) => logs.push('REQFAIL: ' + r.url().slice(-40)));
await p.goto('http://localhost/tool/mrds/post/5', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
console.log(logs.slice(0, 6).join('\n'));
await b.close();