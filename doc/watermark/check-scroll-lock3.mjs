import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.evaluate(() => window.scrollTo(0, 900));
await p.waitForTimeout(500);
const beforeRect = await p.evaluate(() => { const c = document.querySelector('.mr-card'); const r = c.getBoundingClientRect(); return { y: Math.round(r.y), h: Math.round(r.height) }; });
await p.locator('.mr-card').first().click();
await p.waitForTimeout(2200);
const afterRect = await p.evaluate(() => { const c = document.querySelector('.mr-card'); const r = c.getBoundingClientRect(); return { y: Math.round(r.y), h: Math.round(r.height) }; });
console.log('背景卡片位置 before:', JSON.stringify(beforeRect), 'after:', JSON.stringify(afterRect), Math.abs(beforeRect.y - afterRect.y) < 3 ? '（画面没跳 ✓）' : '（画面跳了 ✗）');
// 滚轮作用在遮罩上：画面仍不动
await p.mouse.move(180, 520);
await p.mouse.wheel(0, 1500);
await p.waitForTimeout(700);
const wheelRect = await p.evaluate(() => { const c = document.querySelector('.mr-card'); return Math.round(c.getBoundingClientRect().y); });
console.log('滚轮后背景卡片 y:', wheelRect, Math.abs(wheelRect - beforeRect.y) < 3 ? '（仍没动 ✓）' : '（动了 ✗）');
await p.locator('.mr-sheet-head button', { hasText: '关闭' }).click();
await p.waitForTimeout(700);
const closed = await p.evaluate(() => { const c = document.querySelector('.mr-card'); return { y: Math.round(c.getBoundingClientRect().y), scrollY: Math.round(window.scrollY) }; });
console.log('关闭后:', JSON.stringify(closed), Math.abs(closed.y - beforeRect.y) < 3 ? '（位置还原 ✓）' : '（位置错位 ✗）');
await b.close();