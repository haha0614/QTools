import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.route('**/api/tool/web/capabilities', (r) => r.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ owner: true, loggedIn: true, canSaveToMedia: true }) }));
await p.goto('http://localhost/tool/mrds/post/3305', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
await p.locator('.md-btn', { hasText: '下载' }).first().click();
await p.waitForTimeout(900);
// 工作室
const studio = p.locator('.el-dialog .el-select').nth(1);
await studio.click();
await p.waitForTimeout(300);
await studio.locator('input').fill('测试工作室XYZ');
await p.waitForTimeout(1200);
const sOpts = await p.evaluate(() => { const ds = [...document.querySelectorAll('.el-select-dropdown')].filter((d) => d.offsetParent !== null); return ds.map((d) => [...d.querySelectorAll('.el-select-dropdown__item')].map((e) => e.textContent.trim())); });
console.log('studio dropdowns visible:', JSON.stringify(sOpts));
await p.keyboard.press('Escape');
await p.waitForTimeout(300);
await b.close();