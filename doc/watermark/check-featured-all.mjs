import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3500);
const collapsed = await p.evaluate(() => ({ cards: document.querySelectorAll('.mr-fcard').length, btn: (document.querySelector('.mr-featured-toggle') || {}).textContent?.trim(), sub: (document.querySelector('.mr-featured-sub') || {}).textContent?.trim() }));
console.log('collapsed:', JSON.stringify(collapsed));
await p.locator('.mr-featured-toggle').click();
await p.waitForTimeout(1200);
const expanded = await p.evaluate(() => ({ cards: document.querySelectorAll('.mr-fcard').length, btn: (document.querySelector('.mr-featured-toggle') || {}).textContent?.trim() }));
console.log('expanded:', JSON.stringify(expanded));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-featured-all.png' });
await b.close();