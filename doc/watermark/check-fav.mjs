import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const owner = await p.evaluate(() => window.localStorage.getItem('ms.owner'));
console.log('owner key:', owner ? owner.slice(0, 8) + '…' : null);
const chipBefore = await p.evaluate(() => [...document.querySelectorAll('.mr-dates .mr-chip')].map((c) => c.textContent.trim()).filter((t) => t.indexOf('收藏') >= 0));
console.log('chips before:', JSON.stringify(chipBefore));
const firstCard = p.locator('.mr-card').first();
await firstCard.hover();
await p.waitForTimeout(300);
await firstCard.locator('.mr-fav').click({ force: true });
await p.waitForTimeout(1200);
const afterFav = await p.evaluate(() => ({ favOn: document.querySelectorAll('.mr-fav.on').length, chip: [...document.querySelectorAll('.mr-dates .mr-chip')].map((c) => c.textContent.trim()).find((t) => t.indexOf('收藏') >= 0) }));
console.log('after fav:', JSON.stringify(afterFav));
// 刷新看持久化
await p.reload({ waitUntil: 'networkidle' });
await p.waitForTimeout(3500);
const persisted = await p.evaluate(() => ({ favOn: document.querySelectorAll('.mr-fav.on').length, chip: [...document.querySelectorAll('.mr-dates .mr-chip')].map((c) => c.textContent.trim()).find((t) => t.indexOf('收藏') >= 0), seen: document.querySelectorAll('.mr-seen').length }));
console.log('after reload:', JSON.stringify(persisted));
// 打开一条详情 → 应该标记看过
await p.locator('.mr-card').nth(2).click();
await p.waitForTimeout(2500);
await p.keyboard.press('Escape');
await p.waitForTimeout(500);
const modalOpen = await p.evaluate(() => !!document.querySelector('.mr-sheet'));
console.log('modal opened:', modalOpen);
await p.reload({ waitUntil: 'networkidle' });
await p.waitForTimeout(3500);
const seenAfter = await p.evaluate(() => document.querySelectorAll('.mr-seen').length);
console.log('seen badges after reload:', seenAfter);
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-fav.png' });
await b.close();