import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3200);
const all = await p.evaluate(() => ({ pinned: document.querySelectorAll('.mr-pcard').length, titles: [...document.querySelectorAll('.mr-ptitle')].map((t) => t.textContent.slice(0, 12)) }));
console.log('全部时置顶块:', JSON.stringify(all));
await p.locator('.mr-bar .mr-chip', { hasText: '必撸大赛' }).first().click();
await p.waitForTimeout(2200);
const cat = await p.evaluate(() => ({ pinned: document.querySelectorAll('.mr-pcard').length }));
console.log('选中分类后:', JSON.stringify(cat));
await p.locator('.mr-bar .mr-chip', { hasText: '全部' }).first().click();
await p.waitForTimeout(2200);
const back = await p.evaluate(() => ({ pinned: document.querySelectorAll('.mr-pcard').length }));
console.log('回到全部:', JSON.stringify(back));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-pinned-all.png' });
await b.close();