import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1905, height: 929 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(2500);
const chips = await p.evaluate(() => [...document.querySelectorAll('.mr-dates .mr-chip')].map((c) => (c.textContent || '').trim()));
console.log('date chips:', JSON.stringify(chips));
await p.locator('.mr-dates .mr-chip', { hasText: '近 3 天' }).click();
await p.waitForTimeout(2500);
const state = await p.evaluate(() => { const cards = [...document.querySelectorAll('.mr-card')]; const on = document.querySelector('.mr-dates .mr-chip.on'); return { on: on ? on.textContent.trim() : '', cards: cards.length, first: cards[0] ? (cards[0].innerText || '').split('\n').filter(Boolean).pop() : '', imgs: cards.filter((c) => { const i = c.querySelector('img'); return i && i.naturalWidth > 0; }).length }; });
console.log('after click:', JSON.stringify(state));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-date-filter.png' });
await b.close();