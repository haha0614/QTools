import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
const reqs = [];
p.on('request', (r) => { const u = r.url(); if (u.includes('/tool/web/posts')) reqs.push(u.replace('http://localhost/api','')); });
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
const deep = await p.evaluate(async () => {
  const r = await fetch('/api/tool/web/posts?page=12&size=24');
  const j = await r.json();
  const row = (j.rows || [])[0];
  localStorage.setItem('ms.mrds.scrollAnchor', JSON.stringify({ id: row.id, title: row.title, page: 12, top: 120, at: Date.now() }));
  return row.id;
});
await p.reload({ waitUntil: 'domcontentloaded' });
await p.waitForTimeout(4500);
await p.locator('.mr-resume button', { hasText: '回去' }).click();
await p.waitForTimeout(2500);
reqs.length = 0;
const btn = p.locator('.mr-newer button', { hasText: '加载更新的' });
console.log('按钮数量:', await btn.count(), '| 文案:', await btn.first().textContent());
await btn.first().click();
await p.waitForTimeout(2000);
console.log('点击产生的请求:', JSON.stringify(reqs));
console.log('state:', await p.evaluate(() => ({ y: Math.round(window.scrollY), cards: document.querySelectorAll('[data-post-id]').length })));
await b.close();