import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
p.on('console', (m) => { if (m.type() === 'error') console.log('ERR:', m.text().slice(0, 200)); });
p.on('pageerror', (e) => console.log('PAGEERR:', String(e.message).slice(0, 200)));
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.evaluate(() => window.scrollTo(0, 3000));
await p.waitForTimeout(1200);
await p.locator('[data-post-id]').nth(2).click();
await p.waitForTimeout(1500);
await p.locator('.mr-sheet-head button', { hasText: '展开整页' }).click();
await p.waitForTimeout(2000);
const snap = await p.evaluate(() => { const raw = sessionStorage.getItem('ms.mrds.listState'); return raw ? JSON.parse(raw).scrollY : 'none'; });
console.log('快照 scrollY:', snap);
await p.locator('.mp-back').click();
await p.waitForTimeout(2500);
const st = await p.evaluate(() => ({ y: Math.round(window.scrollY), hidden: getComputedStyle(document.querySelector('.mrds')).visibility, cards: document.querySelectorAll('[data-post-id]').length, h: document.documentElement.scrollHeight }));
console.log('落定:', JSON.stringify(st));
await b.close();