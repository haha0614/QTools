import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1890, height: 922 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(2500);
const chips = await p.evaluate(() => [...document.querySelectorAll('.mr-chip')].filter((c) => /^(横屏|竖屏)/.test((c.textContent || '').trim())).map((c) => (c.textContent || '').trim()));
console.log('方向选项:', JSON.stringify(chips));
const before = await p.evaluate(() => ({ featured: !!document.querySelector('.mr-featured'), cards: document.querySelectorAll('[data-post-id]').length }));
await p.evaluate(() => [...document.querySelectorAll('.mr-chip')].find((c) => (c.textContent || '').startsWith('横屏')).click());
await p.waitForTimeout(3500);
const after = await p.evaluate(() => ({ featured: !!document.querySelector('.mr-featured'), cards: document.querySelectorAll('[data-post-id]').length, activeChip: [...document.querySelectorAll('.mr-chip.on')].map((c) => (c.textContent || '').trim()).slice(0, 6) }));
console.log('筛选前:', JSON.stringify(before));
console.log('筛选后:', JSON.stringify(after));
await b.close();