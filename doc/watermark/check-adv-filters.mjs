import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e.message).slice(0, 90)));
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(4500);
const adv = await p.evaluate(() => ({ toggle: !!document.querySelector('.mr-adv-toggle'), open: !!document.querySelector('.mr-adv'), catsH: Math.round(document.querySelector('.mr-cats').getBoundingClientRect().height) }));
console.log('更多筛选按钮:', JSON.stringify(adv));
await p.locator('.mr-adv-toggle').click();
await p.waitForTimeout(500);
await p.evaluate(() => { const b2 = [...document.querySelectorAll('.mr-adv .mr-chip')].find((x) => x.textContent.trim() === '视频'); b2.click(); });
await p.waitForTimeout(2200);
const v1 = await p.evaluate(() => ({ cards: document.querySelectorAll('[data-post-id]').length, firstHasVideo: !!document.querySelector('.mr-card .mr-play'), text: (document.querySelector('.mr-total') || {}).textContent || '' }));
console.log('筛“视频”后:', JSON.stringify(v1));
await p.evaluate(() => { const b2 = [...document.querySelectorAll('.mr-adv .mr-chip')].find((x) => x.textContent.trim() === '≥2 段'); b2.click(); });
await p.waitForTimeout(2200);
console.log('再筛“≥2 段”:', JSON.stringify(await p.evaluate(() => ({ cards: document.querySelectorAll('[data-post-id]').length }))));
await p.evaluate(() => { const b2 = [...document.querySelectorAll('.mr-adv .mr-chip')].find((x) => x.textContent.trim() === '图文'); b2.click(); });
await p.waitForTimeout(2200);
console.log('切“图文”后:', JSON.stringify(await p.evaluate(() => ({ cards: document.querySelectorAll('[data-post-id]').length, plays: document.querySelectorAll('.mr-play').length }))));
console.log('errors:', JSON.stringify(errs.slice(0, 2)));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/adv-filters.png' });
await b.close();