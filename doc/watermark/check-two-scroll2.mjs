import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 } });
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(String(e.message).slice(0, 100)));
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(4000);
await p.evaluate(() => document.querySelector('[data-post-id]').click());
await p.waitForTimeout(5000);
const st = await p.evaluate(() => {
  const q = (s) => document.querySelector(s);
  const info = (el) => el ? { ch: el.clientHeight, sh: el.scrollHeight, ov: getComputedStyle(el).overflowY } : null;
  return { side: info(q('.md-side')), main: info(q('.md-main')), body: info(q('.mr-sheet-body')) };
});
console.log('尺寸:', JSON.stringify(st));
const sb = await p.locator('.md-side').boundingBox();
await p.mouse.move(sb.x + sb.width / 2, sb.y + 200);
await p.mouse.wheel(0, 500);
await p.waitForTimeout(600);
const a1 = await p.evaluate(() => ({ side: Math.round(document.querySelector('.md-side').scrollTop), main: Math.round(document.querySelector('.md-main').scrollTop) }));
console.log('滚左栏:', JSON.stringify(a1));
const mb = await p.locator('.md-main').boundingBox();
await p.mouse.move(mb.x + mb.width / 2, mb.y + 200);
await p.mouse.wheel(0, 500);
await p.waitForTimeout(600);
const a2 = await p.evaluate(() => ({ side: Math.round(document.querySelector('.md-side').scrollTop), main: Math.round(document.querySelector('.md-main').scrollTop) }));
console.log('再滚右栏:', JSON.stringify(a2));
console.log('左右独立:', a2.main > 0 && a2.side === a1.side ? '是 ✓' : '否 ✗');
console.log('errors:', JSON.stringify(errs.slice(0,2)));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/two-scroll-modal.png' });
await b.close();