import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1300, height: 950 } });
const p = await ctx.newPage();
const ids = {};
await p.goto('https://able.heermtat.cc/archives/page/1/', { waitUntil: 'domcontentloaded', timeout: 45000 });
await p.waitForTimeout(2000);
ids.archive = await p.evaluate(() => { const o = []; for (const a of document.querySelectorAll('.archive-title a, a[href*="/archives/"]')) { const m = (a.getAttribute('href') || '').match(/\/archives\/(\d+)\/?/); if (m && !o.includes(m[1])) o.push(m[1]); if (o.length >= 12) break; } return o; });
await p.goto('https://able.heermtat.cc/category/mrds/', { waitUntil: 'domcontentloaded', timeout: 45000 });
await p.waitForTimeout(2000);
ids.cat = await p.evaluate(() => { const o = []; for (const a of document.querySelectorAll('a[href*="/archives/"]')) { const m = (a.getAttribute('href') || '').match(/\/archives\/(\d+)\/?/); if (m && !o.includes(m[1])) o.push(m[1]); if (o.length >= 12) break; } return o; });
console.log(JSON.stringify(ids));
await b.close();