import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 950 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds', { waitUntil: 'domcontentloaded', timeout: 60000 });
await p.waitForTimeout(5000);
await p.evaluate(() => window.scrollTo(0, 2000));
await p.waitForTimeout(1200);
const before = await p.evaluate(() => ({ y: Math.round(window.scrollY), cards: document.querySelectorAll('[data-post-id]').length }));
await p.locator('[data-post-id]').nth(2).click();
await p.waitForTimeout(1500);
const [newTab] = await Promise.all([ctx.waitForEvent('page'), p.locator('.mr-sheet-head button', { hasText: '展开整页' }).click()]);
await newTab.waitForLoadState('domcontentloaded');
console.log('新标签 URL:', newTab.url());
await newTab.close();
await p.waitForTimeout(800);
const after = await p.evaluate(() => ({ y: Math.round(window.scrollY), cards: document.querySelectorAll('[data-post-id]').length, mask: !!document.querySelector('.mr-mask') }));
console.log('原列表 before:', JSON.stringify(before), 'after:', JSON.stringify(after), before.y === after.y && before.cards === after.cards ? '（原样保持 ✓）' : '（变了 ✗）');
await b.close();