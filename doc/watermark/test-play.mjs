import { chromium } from 'playwright-core';
const id = process.argv[2] || '2';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--autoplay-policy=no-user-gesture-required','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
const errs = [];
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 160)); });
const netFail = [];
p.on('response', (r) => { const u = r.url(); if (u.indexOf('/api/tool/web/hls/') >= 0 && r.status() >= 400) netFail.push(r.status() + ' ' + u.slice(-70)); });
await p.goto('http://localhost/tool/mrds/post/' + id, { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(4000);
const before = await p.evaluate(() => { const v = document.querySelector('video'); return v ? { src: v.src.slice(0, 40), ready: v.readyState, dur: v.duration, err: v.error && v.error.code } : null; });
console.log('before:', JSON.stringify(before));
await p.evaluate(() => { const v = document.querySelector('video'); if (v) { v.muted = true; v.play().catch(() => {}); } });
await p.waitForTimeout(8000);
const after = await p.evaluate(() => { const v = document.querySelector('video'); if (!v) return null; const buf = v.buffered.length ? [v.buffered.start(0), v.buffered.end(0)] : null; return { ready: v.readyState, dur: Math.round(v.duration * 10) / 10, t: Math.round(v.currentTime * 10) / 10, paused: v.paused, buffered: buf, w: v.videoWidth, h: v.videoHeight }; });
console.log('after:', JSON.stringify(after));
console.log('netFail:', JSON.stringify(netFail.slice(0, 4)));
console.log('console errs:', JSON.stringify(errs.slice(0, 4)));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-play.png' });
await b.close();