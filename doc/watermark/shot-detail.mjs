import { chromium } from 'playwright-core';
const id = process.argv[2];
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: false, args: ['--mute-audio','--window-position=-32000,-32000'] });
const ctx = await b.newContext({ viewport: { width: 1600, height: 1000 } });
const p = await ctx.newPage();
await p.goto('http://localhost/tool/mrds/post/' + id, { waitUntil: 'networkidle', timeout: 60000 });
await p.waitForTimeout(3000);
const d = await p.evaluate(() => { const imgs = [...document.querySelectorAll('img')]; return { total: imgs.length, ok: imgs.filter((i) => i.naturalWidth > 0).length, broken: imgs.filter((i) => i.complete && i.naturalWidth === 0).map((i) => i.src.slice(-50)).slice(0, 5) }; });
console.log('detail:', JSON.stringify(d));
await p.screenshot({ path: 'E:/111/project/QTools/doc/shots/mrds-detail.png' });
await b.close();