package com.qtools.media.support;

/**
 * 画面理解提示词（P5.53 交付 2「视觉摘要」）：视觉模型逐帧写一句客观描述。
 *
 * <h2>为什么要「一句客观描述」而不是「让视觉模型直接写梗概」</h2>
 *
 * <p>实测 3B 级视觉模型直接写 200 字梗概时会跑偏（复述画面里根本不存在的剧情、把壁纸动画
 * 说成「一对情侣在教室里」）。拆成两步后，每一步都只做它擅长的事：</p>
 * <ol>
 *   <li><b>逐帧</b>：视觉模型只回答「这一帧有什么」（人物 / 场景 / 动作 / 服装 / 光线），
 *       每帧 30-60 字，禁止推测前后因果；</li>
 *   <li><b>合成</b>：文本模型把这些描述当素材，写 2-3 句中文梗概（见 {@link SynopsisPrompt#vision}）。</li>
 * </ol>
 *
 * <p>固定文案、不含变量：同一批帧两次运行的结果才可比。</p>
 *
 * @author qtools
 */
public final class VisionPrompt
{
    /**
     * 单帧描述提示（固定）
     *
     * <p>「看不到就直说」这一条必须有：壁纸 / 纯色 / 空镜帧占相当比例，否则模型会硬编。</p>
     */
    public static final String FRAME = "这是一部视频里的一帧画面。只描述你在这一帧里看到的内容："
            + "画面中的人物（有几位、在做什么）、场景与物品、服装或造型、光线与色调。"
            + "用一句中文客观描述，不超过 60 字；不要推测前后剧情，不要提到这是视频的哪一部分，"
            + "不要加编号或引号。如果画面里没有可辨认的内容（纯色、模糊、只看到文字或图标），"
            + "只回答：无有效画面";

    /** 单帧描述为空时的哨兵（与 {@link #FRAME} 的约定一致） */
    public static final String NO_CONTENT = "无有效画面";

    private VisionPrompt()
    {
    }
}
